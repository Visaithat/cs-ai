export const PHASE_ICONS: Record<number, LucideIcon> = {
  1: Terminal,
  2: Database,
  3: Sparkles,
  4: Layers,
  5: Shield,
  6: Award,
};

export function LessonGlyph({
  icon,
  size = 18,
  className = "",
}: {
  icon?: LessonIconId;
  size?: number;
  className?: string;
}) {
  const Icon = icon ? LESSON_ICONS[icon] : BookOpen;
  return <Icon size={size} strokeWidth={1.75} aria-hidden="true" className={className} />;
}

export function PhaseGlyph({
  phase,
  size = 18,
  className = "",
}: {
  phase: number;
  size?: number;
  className?: string;
}) {
  const Icon = PHASE_ICONS[phase] ?? BookOpen;
  return <Icon size={size} strokeWidth={1.75} aria-hidden="true" className={className} />;
}

