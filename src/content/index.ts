/**
 * The 180-day catalogue (days 1–180), derived from `schedule.ts`. An entry is `authored` exactly
 * when its lesson id is in `LESSONS`; every other day gets a preview page at the same stable route.
 */
export const LIBRARY: LibraryEntry[] = buildLibrary(new Set(LESSON_IDS));

export function getLibraryEntry(day: number): LibraryEntry | undefined {
  return LIBRARY[day - 1];
}

/** Every id that has a route: all of d001 … d180. Used by `generateStaticParams`. */
export const LESSON_ROUTE_IDS: string[] = LIBRARY.map((entry) => entry.id);

export type LessonRoute =
  | { kind: "authored"; lesson: Lesson; entry: LibraryEntry }
  | { kind: "preview"; entry: LibraryEntry };

/** Decide what `/lesson/[id]` renders: the full lesson, a metadata preview, or nothing (404). */
export function resolveLessonRoute(id: string): LessonRoute | null {
  const day = parseLessonId(id);
  if (day === null) return null;
  const entry = getLibraryEntry(day);
  if (!entry) return null;
  const lesson = getLesson(id);
  return lesson ? { kind: "authored", lesson, entry } : { kind: "preview", entry };
}

